// Regenerate Go's Unicode filter from the exact github-slugger version used by rehype-slug.
// Run from site/: npx tsx scripts/slugger-table.ts
import fs from "node:fs/promises";
import { regex } from "github-slugger/regex.js";
const ranges: [number, number][] = [];
let start = -1;
for (let rune = 0; rune <= 0x110000; rune++) {
  regex.lastIndex = 0;
  const keep =
    rune < 0x110000 &&
    !(rune >= 0xd800 && rune <= 0xdfff) &&
    !regex.test(String.fromCodePoint(rune));
  if (keep && start < 0) start = rune;
  if (!keep && start >= 0) {
    ranges.push([start, rune - 1]);
    start = -1;
  }
}
await fs.writeFile(
  "../api/internal/markdown/slugger_ranges.go",
  `// Code generated by site/scripts/slugger-table.ts; DO NOT EDIT.
// Unicode filter from github-slugger 2.0.0 (MIT; see github-slugger-LICENSE.txt).
package markdown
var sluggerRanges = [][2]rune{\n${ranges.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}},`).join("\n")}\n}\n`,
);
